    /**
     * The Lucide name for a Heroicon name (`user`, `o-user` or `heroicon-o-user`).
     */
    public static function toLucide(string $heroicon): string
    {
        return self::MAP[self::normalize($heroicon)] ?? self::FALLBACK;
    }

    public static function has(string $heroicon): bool
    {
        return isset(self::MAP[self::normalize($heroicon)]);
    }

    /**
     * Whether a name uses the Blade Icons Heroicon prefixes (`heroicon-o-user`).
     */
    public static function isHeroiconName(string $name): bool
    {
        return preg_match('/^heroicon-[osmc]-[a-z0-9-]+$/', $name) === 1;
    }

    private static function normalize(string $heroicon): string
    {
        return (string) preg_replace('/^(?:heroicon-)?[osmc]-/', '', $heroicon);
    }
